const DICTS = { ru, en };
let lang = 'ru';

export const LANGS = ['ru', 'en'];

export function detectLang() {
  return (navigator.language || 'ru').toLowerCase().startsWith('ru') ? 'ru' : 'en';
}

export function setLang(l) {
  lang = DICTS[l] ? l : 'ru';
  document.documentElement.lang = lang;
}

export const getLang = () => lang;

export function t(key, vars = {}) {
  const s = DICTS[lang][key] ?? ru[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

// Localized field from data objects like { ru, en }.
export const tr = (obj) => obj?.[lang] ?? obj?.ru ?? '';

export function weekdayShort(isoDay) {
  // 2024-01-01 was a Monday.
  const d = new Date(2024, 0, isoDay);
  return d.toLocaleDateString(lang, { weekday: 'short' });
}

export function weekdayLong(date) {
  return date.toLocaleDateString(lang, { weekday: 'long', day: 'numeric', month: 'long' });
}
